'use strict';
/**
 * Writes probe-suggested-places.sql: the SQL of « Lieux proposés » day 2 that
 * only the LIVE database can run, run on the live database, read-only.
 *
 *   node investigations/probe-suggested-places.js      (re)write the .sql
 *
 * ── Why generated ───────────────────────────────────────────────────────────
 * The statements must be the ones the shim sends, not a copy that drifts. So
 * this calls the real modules -- suggested-places.js's liveGeo(), and
 * places.js's autocomplete / details / labels -- with a pool that RECORDS each
 * statement instead of running it, and writes them as PREPARE + EXECUTE.
 * tests/probe-suggested-places.test.js regenerates and compares: change the
 * SQL in the shim and not here, and that test fails.
 *
 * ── Why a temporary copy of the table ──────────────────────────────────────
 * The live movin.suggested_place is empty, and has no `locality` until the
 * day-2 release. The probe makes pg_temp.suggested_place (LIKE the live one,
 * plus `locality`), puts four test proposals in it, and points the shim's
 * statements at it. pg_temp is this session's own schema: everything in it is
 * gone when psql exits, and movin is never written. The map (geo.place), the
 * service areas and movin.place_type_of are read live -- the point.
 */
const fs = require('fs');
const path = require('path');

const SHIM = path.join(__dirname, '..', 'stack', 'maps-shim');
const OUT = path.join(__dirname, 'probe-suggested-places.sql');

const CHURCH = '(église|eglise|cathédrale|cathedrale|chapelle|church|chapel|temple|كنيسة)';

/** A pool that records each statement and answers nothing. */
function recorder() {
  const seen = [];
  return {
    seen,
    async query(text, params) { seen.push({ text: String(text), params }); return { rows: [] }; },
    async connect() { return { query: this.query.bind(this), release() {} }; },
  };
}

const quietRes = () => ({ writeHead() {}, end() {} });
const tidy = (sql) => sql.replace(/\n {6,}/g, '\n  ').trim();

/** The statements, captured from the real code. */
async function capture() {
  const out = {};
  const { liveGeo } = require(path.join(SHIM, 'suggested-places.js'));
  const rec = recorder();
  const geo = liveGeo(rec);
  await geo.countryAt(0, 0);
  await geo.localityAt(0, 0);
  await geo.osmNear(0, 0, 100);
  await geo.osmOfType('cafe', 0, 0, 5000, 20);
  await geo.localitiesInArabic(['x']);
  [out.countryAt, out.localityAt, out.osmNear, out.osmOfType, out.localitiesInArabic] = rec.seen.map((s) => s.text);

  const places = require(path.join(SHIM, 'places.js'));
  const p = recorder();
  places.usePool(p);
  const q = (s) => new URLSearchParams(s);
  await places.autocomplete(q('input=probe&location=18.0858,-15.9785'), quietRes());
  out.approvedMatching = p.seen.find((s) => /from movin\.suggested_place/.test(s.text)).text;
  p.seen.length = 0;
  await places.placeDetails(q('place_id=u1'), quietRes());
  out.approvedPlace = p.seen[0].text;
  p.seen.length = 0;
  await places.placeLabels(q('lang=ar&ids=u1'), quietRes());
  out.labels = p.seen[0].text;
  return out;
}

/** movin.suggested_place -> pg_temp.suggested_place, refusing a rewrite that matches nothing. */
function toCopy(sql, name) {
  const n = sql.split('movin.suggested_place').length - 1;
  if (n < 1) throw new Error(`${name}: no movin.suggested_place to point at the copy`);
  return sql.split('movin.suggested_place').join('pg_temp.suggested_place');
}

async function build() {
  const s = await capture();
  for (const k of ['approvedMatching', 'approvedPlace', 'labels']) s[k] = toCopy(s[k], k);

  const prep = (name, sql) => `PREPARE ${name} AS\n  ${tidy(sql)};`;
  const run = (title, stmt, args) => `\\echo '--- ${title}'\nEXECUTE ${stmt}(${args});`;

  const lines = [];
  const L = (...x) => lines.push(...x);
  L(`-- GENERATED by investigations/probe-suggested-places.js -- do not edit; run that.
--
-- « Lieux proposés », day 2: the statements maps-shim sends that only the
-- live database can run (PostGIS, the place index, movin.place_type_of), run
-- on the live database before the release. Read-only for every real table:
-- writes go to pg_temp only (this session's schema, gone when psql exits).
--
--   scp investigations/probe-suggested-places.sql ny:/tmp/
--   ssh ny 'docker exec -i ny-postgres psql -U postgres -d atlas_dev -X -q < /tmp/probe-suggested-places.sql' | tee ~/probe-suggested-places.log
--
-- What to read in the log: each « --- » line is one call the shim will make,
-- with its answer and its time. Every statement must run (ON_ERROR_STOP);
-- the expected answers are written in the line before each.`);
  L('', '\\set ON_ERROR_STOP on', '\\pset footer off', "SET statement_timeout = '60s';", '\\timing on', '');

  L(`\\echo '=== 0. a copy of the table, in pg_temp, with day 2''s locality and four test proposals'`,
    'CREATE TEMP TABLE suggested_place (LIKE movin.suggested_place INCLUDING ALL);',
    'ALTER TABLE pg_temp.suggested_place ADD COLUMN IF NOT EXISTS locality text;',
    `INSERT INTO pg_temp.suggested_place
       (proposed_name, proposed_type, name, type, name_ar, lat, lon, country, locality,
        author_side, author_id, status, decided_at, decided_by_email)
SELECT v.n, v.t, v.n, v.t, v.ar, v.lat, v.lon, v.c,
       geo.locality_of(st_setsrid(st_makepoint(v.lon, v.lat), 4326)::geography),
       'rider', 'probe', v.s,
       CASE WHEN v.s = 'approved' THEN now() END,
       CASE WHEN v.s = 'approved' THEN 'probe@mova' END
  FROM (VALUES
    ('Café Sonde Tfeila',     'cafe',     'مقهى المسبار',   18.0901::float8, -15.9702::float8, 'MR', 'approved'),
    ('Marché Sonde Ksar',     'market',   NULL,             18.1105,         -15.9512,         'MR', 'approved'),
    ('Pharmacie Sonde Hydra', 'pharmacy', 'صيدلية المسبار', 36.7425,           3.0434,         'DZ', 'approved'),
    ('Café Sonde En Attente', 'cafe',     NULL,             18.0870,         -15.9760,         'MR', 'pending')
  ) v(n, t, ar, lat, lon, c, s)
 ORDER BY v.n = 'Café Sonde En Attente', v.lat;`,
    "SELECT place_id, name, type, status, country, locality FROM pg_temp.suggested_place ORDER BY id;", '');

  L(`\\echo '=== 1. countryAt: MR, DZ, MR, DZ, then NO ROW for Rabat (outside both)'`, prep('country_at', s.countryAt),
    run('Nouakchott', 'country_at', '18.0858, -15.9785'), run('Algiers', 'country_at', '36.7538, 3.0588'),
    run('Nouadhibou', 'country_at', '20.9420, -17.0362'), run('Tamanrasset', 'country_at', '22.7850, 5.5228'),
    run('Rabat (expect no row)', 'country_at', '34.0209, -6.8416'), '');

  L(`\\echo '=== 2. localityAt: a town or district for each, possibly NULL in the empty desert'`, prep('locality_at', s.localityAt),
    run('Nouakchott', 'locality_at', '18.0858, -15.9785'), run('Algiers', 'locality_at', '36.7538, 3.0588'),
    run('Tamanrasset', 'locality_at', '22.7850, 5.5228'), run('the desert, 23.5 N 12 W', 'locality_at', '23.5, -12.0'), '');

  L(`\\echo '=== 3. osmNear (the duplicate test): OSM places within 100 m of each centre'`, prep('osm_near', s.osmNear),
    run('Nouakchott, 100 m', 'osm_near', '18.0858, -15.9785, 100'), run('Algiers, 100 m', 'osm_near', '36.7538, 3.0588, 100'), '');

  L(`\\echo '=== 4. osmOfType (search by type): 5 km first, 15 km when 5 finds nothing'`, prep('osm_of_type', s.osmOfType),
    run('cafés, Nouakchott, 5 km', 'osm_of_type', "'cafe', 18.0858, -15.9785, 5000, 20"),
    run('cafés, Algiers, 5 km (12 s on 2026-11-09 with the per-row Arabic join; expect well under a second)', 'osm_of_type', "'cafe', 36.7538, 3.0588, 5000, 20"),
    `\\echo '--- how Postgres runs that, the densest case'`,
    "EXPLAIN (ANALYZE, BUFFERS, COSTS OFF) EXECUTE osm_of_type('cafe', 36.7538, 3.0588, 5000, 20);",
    run('markets, Nouakchott, 5 km', 'osm_of_type', "'market', 18.0858, -15.9785, 5000, 20"),
    run('markets, Nouakchott, 15 km', 'osm_of_type', "'market', 18.0858, -15.9785, 15000, 20"),
    run('pharmacies, Tamanrasset, 5 km', 'osm_of_type', "'pharmacy', 22.7850, 5.5228, 5000, 20"),
    run('pharmacies, Tamanrasset, 15 km', 'osm_of_type', "'pharmacy', 22.7850, 5.5228, 15000, 20"),
    run('mosques, Algiers, 15 km (no church in the list)', 'osm_of_type', "'mosque', 36.7538, 3.0588, 15000, 20"),
    `\\echo '--- churches that place_type_of puts under mosque within 15 km of Algiers -- expect 0'`,
    `SELECT count(*) AS churches_as_mosques
  FROM geo.place p
 WHERE p.kind = 'poi'
   AND st_dwithin(p.geog, st_setsrid(st_makepoint(3.0588, 36.7538), 4326)::geography, 15000)
   AND movin.place_type_of(p.class, p.subclass, p.display_name) = 'mosque'
   AND p.display_name ~* '${CHURCH}';`, '');

  L(`\\echo '=== 5. localitiesInArabic: the Arabic names the index holds for these localities'`,
    prep('localities_ar', s.localitiesInArabic),
    // A literal list: EXECUTE refuses a subquery as a parameter (the first
    // live run, 2026-11-09, stopped here). These are the localities sections 0
    // and 4 returned -- the ones one search by type will ask about at once.
    run('the localities of one search: one query for all', 'localities_ar',
      "ARRAY['Nouakchott', 'E-Nord', 'Las Palmas', 'Ksar', 'Belcourt', 'Sidi M''Hamed', 'El Mouradia', 'Hydra', 'Tamanrasset']"), '');

  L(`\\echo '=== 6. approvedMatching (autocomplete), on the copy: approved only, nearest first'`,
    prep('approved_matching', s.approvedMatching),
    run('« tfeila » -> Café Sonde Tfeila', 'approved_matching', "'tfeila', 18.0858, -15.9785, 3"),
    run('« المسبار » (Arabic name) -> the café, then the Algiers pharmacy', 'approved_matching', "'المسبار', 18.0858, -15.9785, 3"),
    run('« attente » -> nothing (pending is never shown)', 'approved_matching', "'attente', 18.0858, -15.9785, 3"),
    run('« %% » -> nothing (normalises to empty; % is not a wildcard)', 'approved_matching', "'%%', 18.0858, -15.9785, 3"), '');

  L(`\\echo '=== 7. approvedPlace (details, geocode by id): u1 approved, u4 pending -> no row'`,
    prep('approved_place', s.approvedPlace),
    run('u1', 'approved_place', "'u1'"), run('u4 (expect no row)', 'approved_place', "'u4'"), '');

  L(`\\echo '=== 8. labels for u-ids: u1 and u3 (approved, with an Arabic name); not u2 (none), not u4 (pending)'`,
    prep('labels', s.labels),
    run('u1..u4', 'labels', "ARRAY['u1', 'u2', 'u3', 'u4']"), '');

  L(`\\echo '=== done: the copy and the prepared statements end with this session'`, '');
  return lines.join('\n');
}

if (require.main === module) {
  build().then((sql) => {
    fs.writeFileSync(OUT, sql);
    console.log(`wrote ${path.relative(process.cwd(), OUT)} (${sql.split('\n').length} lines)`);
  }).catch((e) => { console.error(e); process.exit(1); });
}

module.exports = { build, OUT };
