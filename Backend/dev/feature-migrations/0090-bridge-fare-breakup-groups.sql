-- Fare breakup groups for the dashboard ride finance info API (GET /ride/{rideId}/financeInfo, `charges`), Bridge only.
--
-- 1. transporter_config.customer_payable_fare_breakup_sub_items_dashboard_config: each top-level entry is a group,
--    its entries are the rows, one row per fare piece. Pieces Bridge does not charge (Indian GST / ambulance /
--    interstate permit, and the driver selected / negotiated fare) are left out. GovtChargesComponent is left out
--    because it is the same amount as RideVatComponent, so listing both would count the VAT twice. EXTERNAL holds
--    the charges paid on to a third party (toll, parking, airport). Rows that are 0 are not sent.
--    Only cities without a value yet are set, as in 0084.
-- 2. Labels, as shared rows (no city), read in the dashboard user's language, else in English. The API takes its
--    groups and rows from the driver app's ride earnings card, so the labels are the card's: a configured group or
--    row is read by its key as ops typed it, as the card reads its own rows, and a key that already has a row keeps
--    that row's text. The adjustments group, which holds the buyer discount, is code-owned: Earnings.Label.Adjustments
--    (Domain.Types.TranslationKeys); the buyer discount keeps the card's own label. Languages: the ones the Bridge
--    and Lynx control centers offer. The non-English texts are machine-written and should be checked by a native
--    speaker.
--
